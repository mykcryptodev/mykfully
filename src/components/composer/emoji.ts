export function findEmoji(query: string) {
  const term = query.trim().toLowerCase().replace(/\s+/g, "_");
  const matches = emojis.filter(([, aliases]) => aliases.includes(term));
  return matches.map(([symbol, aliases]) => ({ symbol, name: aliases.split(" ")[0] }));
}
